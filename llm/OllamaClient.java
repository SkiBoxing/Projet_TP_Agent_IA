package llm;

import org.json.JSONArray;
import org.json.JSONObject;

import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.time.Duration;
import java.util.logging.Level;
import java.util.logging.Logger;

/**
 * minimal client of a local Ollama server (see <a href="https://ollama.com">ollama.com</a>), reused from the
 * {@code sandbox.ollama.agents.AgentLLM} example.
 *
 * @author ANGRAND
 */
public class OllamaClient {

    private static final String DEFAULT_MODEL = "llama3.2";
    private static final Logger logger = Logger.getLogger(OllamaClient.class.getName());

    private final String baseUrl;
    private final HttpClient httpClient;

    public OllamaClient() {
        this("http://localhost:11434");
    }

    public OllamaClient(String baseUrl) {
        this.baseUrl = baseUrl;
        this.httpClient = HttpClient.newBuilder().connectTimeout(Duration.ofSeconds(5)).build();
    }

    /**
     * @return the name of a model available on the local ollama server, or a default guess if none can be listed
     */
    public String pickAvailableModel() {
        try {
            HttpRequest request = HttpRequest.newBuilder().uri(URI.create(baseUrl + "/api/tags")).GET().build();
            HttpResponse<String> response = httpClient.send(request, HttpResponse.BodyHandlers.ofString());
            if (response.statusCode() == 200) {
                JSONArray models = new JSONObject(response.body()).optJSONArray("models");
                if (models != null && !models.isEmpty()) {
                    return models.getJSONObject(0).optString("name", DEFAULT_MODEL);
                }
            }
        } catch (Exception e) {
            logger.log(Level.WARNING, "impossible de lister les modeles ollama", e);
        }
        return DEFAULT_MODEL;
    }

    /**
     * ask a model to generate a single response to a prompt (no chat history)
     *
     * @param model  name of the ollama model to use
     * @param prompt full prompt (system instructions + user request)
     * @return the raw text generated by the model, or null if the server is unreachable or answered with an error
     */
    public String generate(String model, String prompt) {
        try {
            JSONObject jsonRequest = new JSONObject();
            jsonRequest.put("model", model);
            jsonRequest.put("prompt", prompt);
            jsonRequest.put("stream", false);

            HttpRequest request = HttpRequest.newBuilder()
                    .uri(URI.create(baseUrl + "/api/generate"))
                    .header("Content-Type", "application/json")
                    .POST(HttpRequest.BodyPublishers.ofString(jsonRequest.toString()))
                    .timeout(Duration.ofMinutes(2))
                    .build();

            HttpResponse<String> response = httpClient.send(request, HttpResponse.BodyHandlers.ofString());
            if (response.statusCode() == 200) {
                return new JSONObject(response.body()).optString("response", null);
            }
            logger.warning("erreur http " + response.statusCode() + " en appelant ollama");
        } catch (Exception e) {
            logger.log(Level.WARNING, "impossible de contacter le serveur ollama (est-il lance ?)", e);
        }
        return null;
    }
}
